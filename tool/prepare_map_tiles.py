"""Download unmodified Esri imagery for reproducible island map previews.

No labels, masks, or edited imagery are generated by this script.
"""
from concurrent.futures import ThreadPoolExecutor
import json
import math
from pathlib import Path
from urllib.request import urlopen

ROOT = Path(__file__).resolve().parents[1] / "build" / "map-review"
SERVICE = "https://services.arcgisonline.com/ArcGIS/rest/services/World_Imagery/MapServer"
REGIONS = {"hoang-sa": (16.5414, 111.6853), "truong-sa": (8.6444, 111.9192)}
ZOOMS = (3, 5, 8, 11, 15, 19)


def main():
    ROOT.mkdir(parents=True, exist_ok=True)
    with urlopen(SERVICE + "?f=pjson", timeout=30) as response:
        metadata = json.load(response)
    (ROOT / "esri-metadata.json").write_text(json.dumps(metadata, ensure_ascii=False, indent=2), encoding="utf-8")
    tiles = set()
    for lat, lon in REGIONS.values():
        for z in ZOOMS:
            n = 2 ** z
            x = int((lon + 180) / 360 * n)
            y = int((1 - math.asinh(math.tan(math.radians(lat))) / math.pi) / 2 * n)
            tiles.update((z, (x + dx) % n, y + dy) for dx in range(-2, 3) for dy in range(-2, 3)
                         if 0 <= y + dy < n)

    def download(tile):
        z, x, y = tile
        target = ROOT / "tiles" / str(z) / str(x) / f"{y}.jpg"
        if not target.exists():
            with urlopen(f"{SERVICE}/tile/{z}/{y}/{x}", timeout=40) as response:
                data = response.read()
            if not data.startswith((b'\xff\xd8', b'\x89PNG')):
                raise ValueError(f"Not an image: {tile}")
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(data)
        return tile

    with ThreadPoolExecutor(max_workers=8) as pool:
        saved = list(pool.map(download, sorted(tiles)))
    (ROOT / "tile-manifest.json").write_text(json.dumps(dict(service=SERVICE, regions=REGIONS, zooms=ZOOMS,
        tiles=saved, unmodified=True), indent=2), encoding="utf-8")
    print(f"Downloaded {len(saved)} unmodified tiles to {ROOT}")


if __name__ == "__main__":
    main()
